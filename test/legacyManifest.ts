export const withLegacyManifest =
  (request: (input: string, init: RequestInit) => Promise<Response>): typeof fetch =>
  (input, init) => {
    const url = typeof input === 'string' ? input : input instanceof URL ? input.href : input.url;
    return url.endsWith('/tools/v1') && (!init?.method || init.method === 'GET')
      ? Promise.resolve(
          new Response(JSON.stringify(legacyManifest), {
            status: 200,
            headers: { 'content-type': 'application/json' },
          }),
        )
      : request(url, init ?? {});
  };
