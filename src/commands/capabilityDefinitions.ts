export type FieldKind = 'text' | 'integer' | 'boolean' | 'repeat' | 'json' | 'file' | 'clear';
export interface Field {
  flag: string;
  field: string;
  help: string;
  kind: FieldKind;
  required: boolean;
}
export interface Capability {
  path: string;
  description: string;
  argument?: string;
  fields: Field[];
  next: string;
}

