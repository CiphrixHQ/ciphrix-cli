const field = (
  flag: string,
  target = flag.replace(/-([a-z])/g, (_match, letter: string) => letter.toUpperCase()),
  kind: FieldKind = 'text',
  required = false,
  description = help[flag] ?? `value for ${flag}`,
): Field => ({ flag, field: target, kind, required, help: description });
const page = () => [field('page', 'page', 'integer'), field('limit', 'limit', 'integer')];
const sort = () => [field('sort-by'), field('sort-order')];
const spec = (
  path: string,
  description: string,
  argument: string | undefined,
  fields: Field[],
  next: string,
): Capability => ({ path, description, ...(argument && { argument }), fields, next });
const filters = () => [
  field('agent', 'agent', 'repeat'),
  field('action-type', 'actionType', 'repeat'),
  field('status', 'status', 'repeat', false, 'status filter; repeat for multiple values'),
  field('initiator-type', 'initiatorType', 'repeat'),
  field('from'),
  field('to'),
  field('search', 'q'),
  field('limit', 'limit', 'integer'),
];

